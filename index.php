<script>
    document.addEventListener('DOMContentLoaded', function() {
        const counters = document.querySelectorAll('.counter');
        const speed = 300; // Kecepatan animasi (ms)

        // Buat instance dari Intersection Observer
        const observer = new IntersectionObserver(entries => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    // Jalankan fungsi updateCount() jika elemen counter masuk ke dalam tampilan
                    updateCount(entry.target);
                }
            });
        });

        counters.forEach(counter => {
            // Observasi setiap elemen counter
            observer.observe(counter);
        });

        const updateCount = (counter) => {
            const target = +counter.getAttribute('data-target');
            const count = +counter.innerText.replace(/\D/g, ''); // Menghilangkan karakter non-angka

            // Hitung increment
            const increment = target / speed;

            // Pastikan increment minimal 1 untuk menghindari iterasi yang terlalu kecil
            if (count < target) {
                counter.innerText = Math.ceil(count + increment).toLocaleString(); // Format angka
                setTimeout(() => updateCount(counter), 1);
            } else {
                counter.innerText = target.toLocaleString(); // Format angka
            }
        };
    });
</script>
